"""
Pre-processing sanitizer for raw network device configuration dumps.

Responsibilities:
  1. Strip pagination artifacts ("--- More ---", "^H" backspaces, ANSI codes)
  2. Redact obfuscated secrets before text reaches the AI engine
  3. Detect the device vendor from keyword heuristics
"""
import re
from dataclasses import dataclass
from enum import Enum


class VendorType(str, Enum):
    CISCO_IOS = "cisco_ios"
    CISCO_NXOS = "cisco_nxos"
    PALOALTO = "paloalto"
    JUNOS = "junos"
    SONIC = "sonic"
    UNKNOWN = "unknown"


# ── Regex patterns ─────────────────────────────────────────────────────────────

# Pagination / terminal artifacts
_RE_MORE = re.compile(r"--+\s*[Mm]ore\s*--+", re.MULTILINE)
_RE_BACKSPACE = re.compile(r".\x08")              # char followed by backspace
_RE_ANSI = re.compile(r"\x1b\[[0-9;]*[mGKHF]")   # ANSI escape sequences
_RE_CTRL = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f\x7f]")  # control chars (keep \t \n \r)

# Secret patterns to redact (Cisco type-5, type-7, MD5, SHA hashes)
_RE_CISCO_TYPE5 = re.compile(r"(secret\s+5\s+)\S+", re.IGNORECASE)
_RE_CISCO_TYPE7 = re.compile(r"(password\s+7\s+)\S+", re.IGNORECASE)
_RE_CISCO_TYPE8 = re.compile(r"(secret\s+[89]\s+)\S+", re.IGNORECASE)
_RE_SNMP_AUTH = re.compile(r"(auth-password\s+)\S+", re.IGNORECASE)
_RE_SNMP_PRIV = re.compile(r"(privacy-password\s+)\S+", re.IGNORECASE)
_RE_BGP_PASSWD = re.compile(r"(neighbor\s+\S+\s+password\s+)\S+", re.IGNORECASE)
_RE_KEY_STRING = re.compile(r"(key-string\s+(?:\d+\s+)?)\S+", re.IGNORECASE)
_RE_HASH_GENERIC = re.compile(
    r"\$[156]\$[A-Za-z0-9./]{4,}\$[A-Za-z0-9./]{22,}",  # Unix-style crypt
    re.IGNORECASE,
)
_RE_HEX_SECRET = re.compile(
    r"((?:encrypted|hashed|encrypted-password)\s+)([0-9a-fA-F]{32,})",
    re.IGNORECASE,
)

# Vendor detection signatures: keyword → (vendor, weight)
_VENDOR_SIGNATURES: list[tuple[re.Pattern, VendorType, int]] = [
    (re.compile(r"Building configuration", re.I), VendorType.CISCO_IOS, 10),
    (re.compile(r"Current configuration\s*:", re.I), VendorType.CISCO_IOS, 10),
    (re.compile(r"ip ssh version", re.I), VendorType.CISCO_IOS, 8),
    (re.compile(r"^version \d+\.\d+$", re.M), VendorType.CISCO_IOS, 5),
    (re.compile(r"feature\s+\w+", re.I), VendorType.CISCO_NXOS, 6),
    (re.compile(r"Nexus", re.I), VendorType.CISCO_NXOS, 10),
    (re.compile(r"hostname.*\(config\)", re.I), VendorType.CISCO_NXOS, 7),
    (re.compile(r"## Last commit:", re.I), VendorType.JUNOS, 10),
    (re.compile(r"^system \{", re.M), VendorType.JUNOS, 10),
    (re.compile(r"routing-options \{", re.I), VendorType.JUNOS, 8),
    (re.compile(r"set system host-name", re.I), VendorType.JUNOS, 7),
    (re.compile(r"deviceconfig", re.I), VendorType.PALOALTO, 10),
    (re.compile(r"<config version=", re.I), VendorType.PALOALTO, 10),
    (re.compile(r"set deviceconfig system", re.I), VendorType.PALOALTO, 9),
    (re.compile(r"frr version", re.I), VendorType.SONIC, 10),
    (re.compile(r"# Generated by SONiC", re.I), VendorType.SONIC, 10),
    (re.compile(r"sonic-cfggen", re.I), VendorType.SONIC, 8),
]


@dataclass
class SanitizeResult:
    clean_text: str
    vendor: VendorType
    redacted_count: int
    original_line_count: int
    clean_line_count: int


def strip_pagination(text: str) -> str:
    """Remove terminal pagination artifacts and control characters."""
    text = _RE_MORE.sub("", text)
    text = _RE_BACKSPACE.sub("", text)
    text = _RE_ANSI.sub("", text)
    text = _RE_CTRL.sub("", text)
    # Collapse excessive blank lines (keep max 1)
    text = re.sub(r"\n{3,}", "\n\n", text)
    return text.strip()


def redact_secrets(text: str) -> tuple[str, int]:
    """
    Replace password/secret values with <REDACTED>.
    Returns (sanitized_text, count_of_redactions).
    """
    count = 0

    def _sub(pattern: re.Pattern, repl_group: str) -> None:
        nonlocal text, count
        new, n = pattern.subn(rf"\g<1><REDACTED>", text)
        text = new
        count += n

    _sub(_RE_CISCO_TYPE5, r"\1")
    _sub(_RE_CISCO_TYPE7, r"\1")
    _sub(_RE_CISCO_TYPE8, r"\1")
    _sub(_RE_SNMP_AUTH, r"\1")
    _sub(_RE_SNMP_PRIV, r"\1")
    _sub(_RE_BGP_PASSWD, r"\1")
    _sub(_RE_KEY_STRING, r"\1")
    _sub(_RE_HEX_SECRET, r"\1")

    # Generic Unix hash
    new2, n2 = _RE_HASH_GENERIC.subn("<REDACTED>", text)
    text = new2
    count += n2

    return text, count


def detect_vendor(text: str) -> VendorType:
    """
    Score candidate vendors using keyword patterns and return the best match.
    Ties broken by highest cumulative weight.
    """
    scores: dict[VendorType, int] = {}
    for pattern, vendor, weight in _VENDOR_SIGNATURES:
        if pattern.search(text):
            scores[vendor] = scores.get(vendor, 0) + weight
    if not scores:
        return VendorType.UNKNOWN
    return max(scores, key=lambda v: scores[v])


def sanitize(raw_text: str) -> SanitizeResult:
    """
    Full sanitization pipeline:
      1. Strip pagination / control chars
      2. Redact secrets
      3. Detect vendor
    """
    original_lines = raw_text.splitlines()
    clean = strip_pagination(raw_text)
    clean, redacted = redact_secrets(clean)
    vendor = detect_vendor(clean)
    return SanitizeResult(
        clean_text=clean,
        vendor=VendorType(vendor),
        redacted_count=redacted,
        original_line_count=len(original_lines),
        clean_line_count=len(clean.splitlines()),
    )
