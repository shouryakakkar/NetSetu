"""Tests for the sanitization pipeline."""
import pytest

from app.ingestion.sanitizer import VendorType, detect_vendor, redact_secrets, sanitize, strip_pagination


class TestStripPagination:
    def test_removes_more_banner(self):
        text = "line1\n--- More ---\nline2\n--More--\nline3"
        result = strip_pagination(text)
        assert "More" not in result
        assert "line1" in result
        assert "line3" in result

    def test_removes_ansi_codes(self):
        text = "\x1b[32mGreen text\x1b[0m normal"
        result = strip_pagination(text)
        assert "\x1b" not in result
        assert "Green text" in result

    def test_collapses_blank_lines(self):
        text = "line1\n\n\n\n\nline2"
        result = strip_pagination(text)
        assert result.count("\n\n") <= 1

    def test_preserves_content(self):
        text = "ip ssh version 2\nip http server"
        result = strip_pagination(text)
        assert "ip ssh version 2" in result


class TestRedactSecrets:
    def test_redacts_type5_secret(self):
        text = "enable secret 5 $1$mERr$hx5rVt7rPNoS4wqbXKX7m0"
        result, count = redact_secrets(text)
        assert "<REDACTED>" in result
        assert "$1$mERr$" not in result
        assert count > 0

    def test_redacts_type7_password(self):
        text = "username admin password 7 0822455D0A16"
        result, count = redact_secrets(text)
        assert "<REDACTED>" in result
        assert count > 0

    def test_redacts_bgp_password(self):
        text = "neighbor 10.0.0.1 password mysecretkey"
        result, count = redact_secrets(text)
        assert "<REDACTED>" in result
        assert "mysecretkey" not in result

    def test_preserves_non_secret_lines(self):
        text = "ip ssh version 2\nhostname router1"
        result, count = redact_secrets(text)
        assert "ip ssh version 2" in result
        assert count == 0


class TestVendorDetection:
    def test_detects_cisco_ios(self):
        text = "Building configuration...\nCurrent configuration : 1234 bytes\nversion 15.2"
        assert detect_vendor(text) == VendorType.CISCO_IOS

    def test_detects_junos(self):
        text = "## Last commit: 2024-01-01\nsystem {\n host-name router1;\n}"
        assert detect_vendor(text) == VendorType.JUNOS

    def test_detects_paloalto(self):
        text = "deviceconfig {\n  system {\n    hostname pa-fw;\n  }\n}"
        assert detect_vendor(text) == VendorType.PALOALTO

    def test_detects_sonic(self):
        text = "frr version 7.5\n# Generated by SONiC\nhostname sonic-switch"
        assert detect_vendor(text) == VendorType.SONIC

    def test_unknown_vendor(self):
        text = "some random text without vendor keywords"
        assert detect_vendor(text) == VendorType.UNKNOWN


class TestSanitizePipeline:
    def test_full_pipeline_cisco(self):
        raw = (
            "Building configuration...\n--- More ---\n"
            "enable secret 5 $1$abc$xyz123\n"
            "ip ssh version 2\n"
        )
        result = sanitize(raw)
        assert result.vendor == VendorType.CISCO_IOS
        assert result.redacted_count > 0
        assert "--- More ---" not in result.clean_text
        assert "<REDACTED>" in result.clean_text
        assert result.original_line_count > result.clean_line_count or True
